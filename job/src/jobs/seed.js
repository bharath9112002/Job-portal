// Dates are relative to today so the sample data never goes stale.

function daysFromNow(days) {
  const d = new Date()
  d.setDate(d.getDate() + days)
  return d
}
const isoDate = (days) => {
  const d = daysFromNow(days)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}
const posted = (daysAgo) => daysFromNow(-daysAgo).toISOString()

